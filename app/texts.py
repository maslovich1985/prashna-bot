def city_set(name: str, lat: float, lon: float, tz: str) -> str:
    return (
        f"Место установлено: <b>{name}</b>\n"
        f"Координаты: {lat:.4f}, {lon:.4f}\nЧасовой пояс: {tz}\n\n"
        "Теперь просто напишите свой вопрос одним сообщением."
    )


def location_set(lat: float, lon: float, tz: str) -> str:
    return f"Место установлено по геолокации: {lat:.4f}, {lon:.4f} ({tz}).\n\nНапишите свой вопрос."


