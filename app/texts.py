def profile(name: str, lat: float, lon: float, tz: str, left: object, ayanamsa: str) -> str:
    return (
        f"Место: <b>{name}</b> ({lat:.3f}, {lon:.3f}, {tz})\n"
        f"Осталось прашн сегодня: {left}\n"
        f"Аянамша: {ayanamsa}"
    )


def history_row(pid: int, when: str, house: int, question: str) -> str:
    return f"#{pid} · {when} · дом {house}\n   {question}"


def forgotten(n: int) -> str:
    return f"Удалено записей: {n}."


