def prashna_accepted(question: str, when: str, tz: str, place: str, short_chart: str) -> str:
    return (
        f"🕉 <b>Прашна принята</b>\n"
        f"<i>{question}</i>\n\n"
        f"Момент: {when} ({tz}), {place}\n\n" + short_chart
    )


def delivery_failed(pid: int) -> str:
    return (
        "Не удалось отправить толкование целиком — оно сохранено, "
        f"заберите его командой <code>/chart {pid}</code>. Вопрос не списан."
    )


def prashna_footer(pid: int, left: str) -> str:
    return f"Полная карта: <code>/chart {pid}</code> · осталось сегодня: {left}"
